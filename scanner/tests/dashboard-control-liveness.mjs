// A suite that wants to prove some parse/render path issues NO subresource
// request (e.g. the asset dashboard's inert-DOMParser sortKey pin) embeds this
// sentinel in the probe URL it feeds that path. The runner watches every
// Network.requestWillBeSent and fails if the sentinel is ever requested — a
// page-side `window.__pwned` check alone cannot see a request that fires but
// runs no script (an <img src=…> that 404s still leaked the parse).
const FORBIDDEN_REQUEST_SENTINEL = "must-not-load";

// ── run ────────────────────────────────────────────────────────────────────
const userDataDir = mkdtempSync(join(tmpdir(), "claudesec-cdp-"));
let chrome;
let exitCode = 1;
try {
  chrome = spawn(
    chromeBin,
    [
      "--headless=new",
      "--no-sandbox",
      "--disable-gpu",
      "--disable-dev-shm-usage",
      "--no-first-run",
      "--no-default-browser-check",
      "--remote-debugging-port=0",
      `--user-data-dir=${userDataDir}`,
      "about:blank",
    ],
    { stdio: ["ignore", "ignore", "pipe"] }
  );
  chrome.on("error", (e) => {
    console.error("FATAL: failed to spawn Chrome:", e.message);
  });

  const port = await waitForDevtoolsPort(join(userDataDir, "DevToolsActivePort"), 20000);
  const verRes = await fetch(`http://127.0.0.1:${port}/json/version`);
  const { webSocketDebuggerUrl } = await verRes.json();

  const ws = new WebSocket(webSocketDebuggerUrl);
  await new Promise((resolve, reject) => {
    ws.addEventListener("open", resolve, { once: true });
    ws.addEventListener("error", () => reject(new Error("browser WebSocket error")), { once: true });
  });

  const cdp = new CDP(ws);
  const { targetId } = await cdp.send("Target.createTarget", { url: "about:blank" });
  const { sessionId } = await cdp.send("Target.attachToTarget", { targetId, flatten: true });

  await cdp.send("Page.enable", {}, sessionId);
  await cdp.send("Runtime.enable", {}, sessionId);
  await cdp.send("Log.enable", {}, sessionId);
  await cdp.send("Network.enable", {}, sessionId);
  const requestedUrls = [];
  cdp.on("Network.requestWillBeSent", (params, sid) => {
    if (sid === sessionId && params.request && params.request.url) {
      requestedUrls.push(params.request.url);
    }
  });
  await cdp.send("Page.addScriptToEvaluateOnNewDocument", { source: DOCUMENT_START }, sessionId);

  const loaded = cdp.once("Page.loadEventFired", (_p, sid) => sid === sessionId);
  const fileUrl = pathToFileURL(htmlPath).href;
  await cdp.send("Page.navigate", { url: fileUrl }, sessionId);
  await loaded;
  await sleep(150); // let the delegated listeners + document_start settle

  const assertScript = assertFile ? readFileSync(assertFile, "utf8") : ASSERT_CONTROLS;
  const evalRes = await cdp.send(
    "Runtime.evaluate",
    { expression: assertScript, returnByValue: true, awaitPromise: true },
    sessionId
  );
  if (evalRes.exceptionDetails) {
    throw new Error("page evaluation threw: " + JSON.stringify(evalRes.exceptionDetails));
  }
  const { results, violations } = evalRes.result.value;

  // ── report ────────────────────────────────────────────────────────────────
  console.log("=== dashboard control-liveness ===");
  let dead = 0;
  let skipped = 0;
  for (const r of results) {
    const tag = r.skip ? "SKIP" : r.ok ? "PASS" : "FAIL";
    console.log(`${tag}: ${r.name} — ${r.detail}`);
    if (r.skip) skipped++;
    else if (!r.ok) dead++;
  }
  // A nonce/CSP regression (reintroduced inline handler, broken nonce) fires a
  // script-src* securitypolicyviolation. A healthy offline dashboard fires none
  // (no external subresources). Fail on ANY violation; flag script-src* loudly.
  const scriptViolations = violations.filter((v) => (v.directive || "").indexOf("script-src") === 0);
  console.log(`CSP self-violations: total=${violations.length} script-src=${scriptViolations.length}`);
  for (const v of violations) {
    console.log(`  VIOLATION: directive=${v.directive} blockedURI=${v.blockedURI} sample="${v.sample}" line=${v.line}`);
  }

  // Forbidden subresource requests (see FORBIDDEN_REQUEST_SENTINEL).
  const forbidden = requestedUrls.filter((u) => u.indexOf(FORBIDDEN_REQUEST_SENTINEL) >= 0);
  console.log(`Forbidden subresource requests: ${forbidden.length}`);
  for (const u of forbidden) console.log(`  LEAKED REQUEST: ${u}`);

  const driven = results.length - skipped;
  // Non-vacuity floor: a suite whose assertions all became SKIPs (or that
  // returned nothing at all, e.g. a selector rename that made every block bail
  // early into a `rec(...)` it no longer reaches) would otherwise print
  // "0/0 live" and exit 0. Zero DRIVEN controls is a failure, not a pass.
  if (driven === 0) {
    console.log("VACUOUS: zero controls were actually driven (all skipped or none returned)");
  }
  const controlsOk = dead === 0 && driven > 0;
  const cspOk = violations.length === 0;
  const requestsOk = forbidden.length === 0;
  console.log(
    `\nRESULT: controls ${driven - dead}/${driven} live, ${skipped} skipped, ` +
      `${violations.length} CSP self-violation(s), ${forbidden.length} forbidden request(s)`
  );
  exitCode = controlsOk && cspOk && requestsOk ? 0 : 1;

  try {
    ws.close();
  } catch (_) {
    /* ignore */
  }
} catch (err) {
  console.error("FATAL:", err && err.stack ? err.stack : String(err));
  exitCode = 1;
} finally {
  if (chrome) {
    try {
      chrome.kill("SIGKILL");
    } catch (_) {
      /* ignore */
    }
  }
  try {
    rmSync(userDataDir, { recursive: true, force: true });
  } catch (_) {
    /* ignore */
  }
}

process.exit(exitCode);
